/**
 * Generate db/migrations/140_seed_foundation_tvsf_demo.sql — a self-contained, idempotent
 * SQL seed of the ENTIRE Foundation TVSF demo (opportunity ingest → tenant/accounts/Paul →
 * library → buckets + scores → bridge/cards → portal/purchase → proposal/sections/matrix),
 * dumped from the live sandbox so JSONB (cards, canvas content, criteria, scores) is exact.
 *
 * Every row is INSERT … ON CONFLICT DO NOTHING (safe to re-run / re-deploy). Passwords are
 * re-hashed in-DB via pgcrypto crypt() (no committed hashes). Run: node scripts/gen-foundation-seed-migration.mjs
 */
import postgres from 'postgres';
import { writeFile } from 'node:fs/promises';

const CONN = process.env.DATABASE_URL;
if (!CONN) { console.error('set DATABASE_URL'); process.exit(1); }
const sql = postgres(CONN, { max: 1, idle_timeout: 5 }); // no transform → snake_case keys
const OUT = 'db/migrations/140_seed_foundation_tvsf_demo.sql';

const FND = `(SELECT id FROM tenants WHERE slug='foundation')`;
const OPP = `(SELECT opportunity_id FROM tenant_opportunity_cards WHERE tenant_id=${FND})`;
const SOLS = `(SELECT id FROM curated_solicitations WHERE opportunity_id IN ${OPP})`;
const PROPS = `(SELECT id FROM proposals WHERE tenant_id=${FND})`;
const ATOMS = `(SELECT id FROM library_atoms WHERE tenant_id=${FND})`;

// FK-safe order: parents before children.
const PLAN = [
  ['opportunities', `WHERE id IN ${OPP}`],
  ['curated_solicitations', `WHERE opportunity_id IN ${OPP}`],
  ['solicitation_compliance', `WHERE solicitation_id IN ${SOLS}`],
  ['solicitation_volumes', `WHERE solicitation_id IN ${SOLS}`],
  ['volume_required_items', `WHERE volume_id IN (SELECT id FROM solicitation_volumes WHERE solicitation_id IN ${SOLS})`],
  ['opportunity_bridge', `WHERE opportunity_id IN ${OPP}`],
  ['tenants', `WHERE slug='foundation'`],
  ['users', `WHERE id IN (SELECT user_id FROM user_memberships WHERE tenant_id=${FND})`],
  ['user_memberships', `WHERE tenant_id=${FND}`],
  ['tenant_spotlight_buckets', `WHERE tenant_id=${FND}`],
  ['tenant_bucket_scores', `WHERE tenant_id=${FND}`],
  ['library_atoms', `WHERE tenant_id=${FND}`],
  ['atom_tags', `WHERE atom_id IN ${ATOMS}`],
  ['tenant_opportunity_cards', `WHERE tenant_id=${FND}`],
  ['tenant_bridge_cursor', `WHERE tenant_id=${FND}`],
  ['proposals', `WHERE tenant_id=${FND}`],
  ['proposal_artifacts', `WHERE proposal_id IN ${PROPS}`],
  ['proposal_sections', `WHERE proposal_id IN ${PROPS}`],
  ['proposal_compliance_matrix', `WHERE proposal_id IN ${PROPS}`],
  ['proposal_collaborators', `WHERE proposal_id IN ${PROPS}`],
  ['collaborator_stage_access', `WHERE proposal_id IN ${PROPS}`],
  ['proposal_portals', `WHERE tenant_id=${FND}`],
  ['purchases', `WHERE tenant_id=${FND}`],
  ['shadow_admin_grants', `WHERE tenant_id=${FND}`],
];

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
async function tableExists(t) {
  const [r] = await sql`SELECT 1 FROM information_schema.tables WHERE table_name=${t} AND table_schema='public'`;
  return !!r;
}
async function colMeta(t) {
  const rows = await sql`SELECT column_name, data_type, is_generated FROM information_schema.columns WHERE table_name=${t} AND table_schema='public'`;
  const types = {};
  const generated = new Set();
  for (const r of rows) { types[r.column_name] = r.data_type; if (r.is_generated === 'ALWAYS') generated.add(r.column_name); }
  return { types, generated }; // generated cols (e.g. full_text_tsv) cannot be inserted
}
function lit(val, type, col, table) {
  if (val === null || val === undefined) return 'NULL';
  if (table === 'users' && col === 'password_hash') return `crypt('DemoPass123!', gen_salt('bf', 12))`;
  switch (type) {
    case 'jsonb': case 'json': return `${q(JSON.stringify(val))}::jsonb`;
    case 'ARRAY': {
      const arr = Array.isArray(val) ? val : [];
      if (!arr.length) return `'{}'`;
      return `'{${arr.map((e) => `"${String(e).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`).join(',')}}'`;
    }
    case 'boolean': return val ? 'true' : 'false';
    case 'integer': case 'bigint': case 'smallint': case 'numeric': case 'real': case 'double precision':
      return String(val);
    case 'timestamp with time zone': case 'timestamp without time zone': case 'date':
      return `${q(val instanceof Date ? val.toISOString() : String(val))}::timestamptz`;
    default: return q(val); // text, uuid, character varying, USER-DEFINED enums, etc.
  }
}

async function run() {
  const out = [
    '-- 140_seed_foundation_tvsf_demo.sql',
    '-- Idempotent DEMO seed: the full Foundation TVSF workspace (opportunity ingest, tenant +',
    '-- founder accounts + Paul the EC shadow-admin, library, spotlight buckets + scores, pipeline',
    '-- cards, comp-purchase portal, and the submitted proposal with sections + compliance matrix).',
    '-- Generated by scripts/gen-foundation-seed-migration.mjs. Demo password: DemoPass123!.',
    '-- Every statement is ON CONFLICT DO NOTHING — safe to re-run / re-deploy.',
    'CREATE EXTENSION IF NOT EXISTS pgcrypto;',
    '',
  ];
  // Audit user-columns often point at the RFP admin who ran the ingest/release — who is NOT
  // part of this customer seed. Null any FK-to-users column whose value isn't a seeded user
  // (the required user FKs — memberships/collaborators — always reference seeded users, so
  // they're never nulled). Discover the FK columns generically.
  const su = await sql.unsafe(`SELECT id FROM users WHERE id IN (SELECT user_id FROM user_memberships WHERE tenant_id=${FND})`);
  const seededUsers = new Set(su.map((r) => r.id));
  const fkRows = await sql.unsafe(`
    SELECT tc.table_name AS t, kcu.column_name AS c
    FROM information_schema.table_constraints tc
    JOIN information_schema.key_column_usage kcu ON kcu.constraint_name=tc.constraint_name AND kcu.table_schema=tc.table_schema
    JOIN information_schema.constraint_column_usage ccu ON ccu.constraint_name=tc.constraint_name AND ccu.table_schema=tc.table_schema
    WHERE tc.constraint_type='FOREIGN KEY' AND ccu.table_name='users' AND ccu.column_name='id'`);
  const userFkCols = new Set(fkRows.map((r) => `${r.t}.${r.c}`));
  let total = 0;
  const solUpdates = []; // opportunities.solicitation_id ↔ curated_solicitations is a circular FK
  for (const [table, where] of PLAN) {
    if (!(await tableExists(table))) { out.push(`-- (skip ${table} — table absent)`); continue; }
    const { types, generated } = await colMeta(table);
    const rows = await sql.unsafe(`SELECT * FROM ${table} ${where}`);
    if (!rows.length) { out.push(`-- ${table}: 0 rows`); continue; }
    const cols = Object.keys(rows[0]).filter((c) => !generated.has(c));
    out.push(`-- ${table} (${rows.length})`);
    for (const r of rows) {
      const vals = cols.map((c) => {
        // Break the opportunities↔curated_solicitations cycle: insert opp with a NULL
        // solicitation_id, then resolve it after the solicitations are inserted.
        if (table === 'opportunities' && c === 'solicitation_id') {
          if (r[c] != null) solUpdates.push(`UPDATE opportunities SET solicitation_id=${lit(r[c], types[c], c, table)} WHERE id=${q(r.id)};`);
          return 'NULL';
        }
        if (userFkCols.has(`${table}.${c}`) && r[c] != null && !seededUsers.has(r[c])) return 'NULL';
        return lit(r[c], types[c], c, table);
      });
      out.push(`INSERT INTO ${table} (${cols.join(', ')}) VALUES (${vals.join(', ')}) ON CONFLICT DO NOTHING;`);
    }
    out.push('');
    total += rows.length;
    console.log(`  ${table}: ${rows.length}`);
    if (table === 'curated_solicitations' && solUpdates.length) {
      out.push('-- resolve the circular opportunities.solicitation_id FK', ...solUpdates, '');
    }
  }
  await writeFile(OUT, out.join('\n') + '\n');
  console.log(`\n✓ wrote ${OUT} — ${total} rows across ${PLAN.length} tables`);
}
run().then(() => sql.end().then(() => process.exit(0))).catch((e) => { console.error(e); sql.end().then(() => process.exit(1)); });
