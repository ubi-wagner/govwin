/**
 * Generate db/migrations/167_seed_dow_2026_dod_solicitations.sql — an idempotent SQL seed of the
 * two real DoW 2026 solicitations (ingested from docs/DoW 2026 SBIR/STTR BAA), captured live so the
 * JSONB (compliance custom_variables, canvas content, format/compliance specs) is exact:
 *   RFP-admin side  — opportunities, curated_solicitations, solicitation_compliance/volumes/items,
 *                     the per-solicitation Technical document_templates, bridge fan-out.
 *   Foundation-tenant side — the OPP card, comp-purchase portal, and the submitted proposal
 *                     (artifacts + all sections + compliance matrix).
 *
 * Every row is INSERT … ON CONFLICT DO NOTHING (safe to re-run / re-deploy). Depends on the base
 * seed (eric/master_admin) + mig 140 (foundation tenant + kate). Run:
 *   DATABASE_URL=… node scripts/gen-dow-seed-migration.mjs
 */
import postgres from 'postgres';
import { writeFile } from 'node:fs/promises';

const CONN = process.env.DATABASE_URL;
if (!CONN) { console.error('set DATABASE_URL'); process.exit(1); }
const sql = postgres(CONN, { max: 1, idle_timeout: 5 });
const OUT = 'db/migrations/167_seed_dow_2026_dod_solicitations.sql';

const FND  = `(SELECT id FROM tenants WHERE slug='foundation')`;
const OPP  = `(SELECT id FROM opportunities WHERE source_id LIKE 'dow-%')`;
const PROPS= `(SELECT id FROM proposals WHERE opportunity_id IN ${OPP} AND tenant_id=${FND})`;
const VOLS = `(SELECT id FROM solicitation_volumes WHERE topic_id IN ${OPP})`;
const TPL  = `WHERE name LIKE 'N261-EXP01%' OR name LIKE 'N26D-CAM07%'`;

// FK-safe order: parents before children. document_templates before volumes (items may carry
// template_id); artifacts before sections; sections before the compliance matrix; proposals
// before portals/purchases.
const PLAN = [
  ['opportunities',              `WHERE id IN ${OPP}`],
  ['curated_solicitations',      `WHERE opportunity_id IN ${OPP}`],
  ['solicitation_compliance',    `WHERE topic_id IN ${OPP}`],
  ['document_templates',         TPL],
  ['solicitation_volumes',       `WHERE topic_id IN ${OPP}`],
  ['volume_required_items',      `WHERE volume_id IN ${VOLS}`],
  ['opportunity_bridge',         `WHERE opportunity_id IN ${OPP}`],
  ['tenant_opportunity_cards',   `WHERE opportunity_id IN ${OPP} AND tenant_id=${FND}`],
  ['proposals',                  `WHERE id IN ${PROPS}`],
  ['proposal_artifacts',         `WHERE proposal_id IN ${PROPS}`],
  ['proposal_sections',          `WHERE proposal_id IN ${PROPS}`],
  ['proposal_compliance_matrix', `WHERE proposal_id IN ${PROPS}`],
  ['proposal_portals',           `WHERE opportunity_id IN ${OPP} AND tenant_id=${FND}`],
  ['purchases',                  `WHERE opportunity_id IN ${OPP} AND tenant_id=${FND}`],
];

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
async function tableExists(t) { const [r] = await sql`SELECT 1 FROM information_schema.tables WHERE table_name=${t} AND table_schema='public'`; return !!r; }
async function colMeta(t) {
  const rows = await sql`SELECT column_name, data_type, is_generated FROM information_schema.columns WHERE table_name=${t} AND table_schema='public'`;
  const types = {}; const generated = new Set();
  for (const r of rows) { types[r.column_name] = r.data_type; if (r.is_generated === 'ALWAYS') generated.add(r.column_name); }
  return { types, generated };
}
function lit(val, type) {
  if (val === null || val === undefined) return 'NULL';
  switch (type) {
    case 'jsonb': case 'json': return `${q(JSON.stringify(val))}::jsonb`;
    case 'ARRAY': { const arr = Array.isArray(val) ? val : []; if (!arr.length) return `'{}'`;
      return `'{${arr.map((e) => `"${String(e).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`).join(',')}}'`; }
    case 'boolean': return val ? 'true' : 'false';
    case 'integer': case 'bigint': case 'smallint': case 'numeric': case 'real': case 'double precision': return String(val);
    case 'timestamp with time zone': case 'timestamp without time zone': case 'date':
      return `${q(val instanceof Date ? val.toISOString() : String(val))}::timestamptz`;
    default: return q(val);
  }
}

async function run() {
  const out = [
    '-- 167_seed_dow_2026_dod_solicitations.sql',
    '-- Idempotent seed of the two REAL DoW 2026 solicitations, ingested from the uploaded BAAs',
    "-- (docs/DoW 2026 SBIR BAA FULL_R1_04132026.pdf, docs/DoW 2026 STTR BAA FULL_04132026.pdf):",
    '--   • DoW 2026 SBIR — Navy (DON) Phase I (N261-EXP01): 6 volumes, Technical 10pp, 12 sections.',
    '--   • DoW 2026 STTR — Direct to Phase II (N26D-CAM07): 6 volumes, Technical 30pp (20 feasibility',
    '--     + 10 snapshot), SB>=40%/RI>=30% work-split, SBC<->RI Allocation of Rights.',
    '-- RFP-admin authored (compliance/volumes/templates) + the Foundation-tenant submitted build.',
    '-- Generated by scripts/gen-dow-seed-migration.mjs. Depends on base seed (eric) + mig 140 (foundation/kate).',
    '-- Every statement is ON CONFLICT DO NOTHING — safe to re-run / re-deploy.',
    'CREATE EXTENSION IF NOT EXISTS pgcrypto;',
    '',
  ];
  // Null user-FK columns that don't reference a seeded user (the RFP admin who ran ingest/release
  // is not part of this seed; every such column is nullable — verified). Foundation users (kate)
  // ARE seeded by mig 140, so their audit FKs are preserved.
  const su = await sql.unsafe(`SELECT id FROM users WHERE id IN (SELECT user_id FROM user_memberships WHERE tenant_id=${FND})`);
  const seededUsers = new Set(su.map((r) => r.id));
  const fkRows = await sql.unsafe(`
    SELECT tc.table_name AS t, kcu.column_name AS c
    FROM information_schema.table_constraints tc
    JOIN information_schema.key_column_usage kcu ON kcu.constraint_name=tc.constraint_name AND kcu.table_schema=tc.table_schema
    JOIN information_schema.constraint_column_usage ccu ON ccu.constraint_name=tc.constraint_name AND ccu.table_schema=tc.table_schema
    WHERE tc.constraint_type='FOREIGN KEY' AND ccu.table_name='users' AND ccu.column_name='id'`);
  const userFkCols = new Set(fkRows.map((r) => `${r.t}.${r.c}`));
  let total = 0;
  const solUpdates = [];
  for (const [table, where] of PLAN) {
    if (!(await tableExists(table))) { out.push(`-- (skip ${table} — table absent)`); continue; }
    const { types, generated } = await colMeta(table);
    const rows = await sql.unsafe(`SELECT * FROM ${table} ${where}`);
    if (!rows.length) { out.push(`-- ${table}: 0 rows`); continue; }
    const cols = Object.keys(rows[0]).filter((c) => !generated.has(c));
    out.push(`-- ${table} (${rows.length})`);
    for (const r of rows) {
      const vals = cols.map((c) => {
        if (table === 'opportunities' && c === 'solicitation_id') {
          if (r[c] != null) solUpdates.push(`UPDATE opportunities SET solicitation_id=${lit(r[c], types[c])} WHERE id=${q(r.id)};`);
          return 'NULL';
        }
        if (userFkCols.has(`${table}.${c}`) && r[c] != null && !seededUsers.has(r[c])) return 'NULL';
        return lit(r[c], types[c]);
      });
      out.push(`INSERT INTO ${table} (${cols.join(', ')}) VALUES (${vals.join(', ')}) ON CONFLICT DO NOTHING;`);
    }
    out.push('');
    total += rows.length;
    console.log(`  ${table}: ${rows.length}`);
    if (table === 'curated_solicitations' && solUpdates.length) {
      out.push('-- resolve the circular opportunities.solicitation_id FK', ...solUpdates, '');
    }
  }
  await writeFile(OUT, out.join('\n') + '\n');
  console.log(`\n✓ wrote ${OUT} — ${total} rows across ${PLAN.length} tables`);
}
run().then(() => sql.end().then(() => process.exit(0))).catch((e) => { console.error(e); sql.end().then(() => process.exit(1)); });
