/**
 * Generate db/migrations/170_seed_foundation_deck_ingest.sql — the Foundation deck atomized
 * through the REAL ingest procedure (POST /atoms/atomize-package → atomizeDocumentIntoLibrary),
 * captured live for durability. Replaces the hand-seeded mig-140 deck atoms (which had NO ingest
 * provenance — cocoon_id/source_anchor null, creator_kind=admin, no cocoon, no librarian task)
 * with genuinely-ingested atoms: a document_cocoon + a reference atom + one anchored primitive per
 * block, all cocoon-linked, plus the queued librarian catalog task. On deploy this migration also
 * soft-archives the mig-140 hand-seeds so the live deck library is the real-ingest one.
 * Generated by scripts/gen-foundation-ingest-seed.mjs. Depends on base seed + mig 140.
 *   DATABASE_URL=… node scripts/gen-foundation-ingest-seed.mjs
 */
import postgres from 'postgres';
import { writeFile } from 'node:fs/promises';

const CONN = process.env.DATABASE_URL;
if (!CONN) { console.error('set DATABASE_URL'); process.exit(1); }
const sql = postgres(CONN, { max: 1, idle_timeout: 5 });
const OUT = 'db/migrations/170_seed_foundation_deck_ingest.sql';

const COCOON = `'3d080499-3bff-4392-9497-173ae4c7102f'`;
const FND = `(SELECT id FROM tenants WHERE slug='foundation')`;

// Order matters for FKs: cocoon → atoms → tags → librarian task.
const PLAN = [
  ['document_cocoons', `WHERE id = ${COCOON}`],
  ['library_atoms',    `WHERE cocoon_id = ${COCOON}`],
  ['atom_tags',        `WHERE atom_id IN (SELECT id FROM library_atoms WHERE cocoon_id = ${COCOON})`],
  ['agent_task_queue', `WHERE agent_role='librarian' AND input->>'cocoonId' = '3d080499-3bff-4392-9497-173ae4c7102f'`],
];

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
async function tableExists(t) { const [r] = await sql`SELECT 1 FROM information_schema.tables WHERE table_name=${t} AND table_schema='public'`; return !!r; }
async function colMeta(t) {
  const rows = await sql`SELECT column_name, data_type, is_generated FROM information_schema.columns WHERE table_name=${t} AND table_schema='public'`;
  const types = {}; const generated = new Set();
  for (const r of rows) { types[r.column_name] = r.data_type; if (r.is_generated === 'ALWAYS') generated.add(r.column_name); }
  return { types, generated };
}
function lit(val, type) {
  if (val === null || val === undefined) return 'NULL';
  switch (type) {
    case 'jsonb': case 'json': return `${q(JSON.stringify(val))}::jsonb`;
    case 'ARRAY': { const arr = Array.isArray(val) ? val : []; if (!arr.length) return `'{}'`;
      return `'{${arr.map((e) => `"${String(e).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`).join(',')}}'`; }
    case 'boolean': return val ? 'true' : 'false';
    case 'integer': case 'bigint': case 'smallint': case 'numeric': case 'real': case 'double precision': return String(val);
    case 'timestamp with time zone': case 'timestamp without time zone': case 'date':
      return `${q(val instanceof Date ? val.toISOString() : String(val))}::timestamptz`;
    // USER-DEFINED covers the vector `embedding` column — emit NULL (demo atoms need no embedding).
    case 'USER-DEFINED': return 'NULL';
    default: return q(val);
  }
}

async function run() {
  const out = [
    '-- 170_seed_foundation_deck_ingest.sql',
    '-- The Foundation deck atomized through the REAL ingest procedure (upload → document_cocoon →',
    '-- atomizeDocumentIntoLibrary → reference atom + anchored primitives → librarian catalog task),',
    '-- captured live for deployment durability. This SUPERSEDES the hand-seeded mig-140 deck atoms,',
    '-- which carried no ingest provenance (cocoon_id/source_anchor NULL, no cocoon, no librarian task).',
    '-- The trailing UPDATE soft-archives the mig-140 hand-seeds so the live deck library is the',
    '-- genuinely-ingested one. Generated by scripts/gen-foundation-ingest-seed.mjs. Depends on mig 140.',
    '-- Every statement is ON CONFLICT DO NOTHING / idempotent — safe to re-run / re-deploy.',
    'CREATE EXTENSION IF NOT EXISTS pgcrypto;',
    '',
  ];
  let total = 0;
  for (const [table, where] of PLAN) {
    if (!(await tableExists(table))) { out.push(`-- (skip ${table} — table absent)`); continue; }
    const { types, generated } = await colMeta(table);
    const rows = await sql.unsafe(`SELECT * FROM ${table} ${where}`);
    if (!rows.length) { out.push(`-- ${table}: 0 rows`); continue; }
    const cols = Object.keys(rows[0]).filter((c) => !generated.has(c));
    out.push(`-- ${table} (${rows.length})`);
    for (const r of rows) {
      const vals = cols.map((c) => lit(r[c], types[c]));
      out.push(`INSERT INTO ${table} (${cols.join(', ')}) VALUES (${vals.join(', ')}) ON CONFLICT DO NOTHING;`);
    }
    out.push('');
    total += rows.length;
    console.log(`  ${table}: ${rows.length}`);
  }
  // Supersede the mig-140 hand-seeded deck atoms (no ingest provenance) — soft archive, reversible.
  out.push('-- Supersede the mig-140 hand-seeded deck atoms (no cocoon/anchor) — soft-archive, reversible.');
  out.push(
    `UPDATE library_atoms SET archived_at = COALESCE(archived_at, now()), updated_at = now()\n` +
    `WHERE tenant_id = ${FND} AND source = 'upload' AND cocoon_id IS NULL\n` +
    `  AND grain = 'primitive' AND archived_at IS NULL;`);
  out.push('');
  await writeFile(OUT, out.join('\n') + '\n');
  console.log(`\n✓ wrote ${OUT} — ${total} rows across ${PLAN.length} tables + archive of the hand-seeds`);
}
run().then(() => sql.end().then(() => process.exit(0))).catch((e) => { console.error(e); sql.end().then(() => process.exit(1)); });
